import { describe, expect, it } from 'vitest';
import { UNAVAILABLE_REASONS } from './api.js';
import { ROUTE_REASONS } from './registry.js';
import { ADMIN_CODES, UNAUTHORIZED_DETAILS } from './admin.js';

/**
 * Словари машинных причин. Проверяется не «работает ли код», а **стиль и
 * состав перечня** — то, из-за чего два похожих словаря расходятся молча и
 * одно состояние получает два имени (Р-087, `_brain/КОНТРАКТЫ.md` §4г).
 *
 * Эталон здесь выписан **из контракта, а не снят с кода**: ожидания, снятые
 * с реализации, закрепляют её ошибку и остаются зелёными навсегда. Если
 * перечень в коде разойдётся с §4г — краснеет этот тест, а не потребитель
 * через месяц.
 *
 * Тест-растяжка: он не проверяет поведение, он **делает видимой связь** между
 * кодом и решением штаба. Тот, кто решит завести восьмую причину прямо в
 * коде, увидит здесь, что имя заводится в §4г.
 */

/** kebab-case: строчные латинские слова через дефис, без цифр по краям. */
const KEBAB = /^[a-z]+(-[a-z]+)*$/;

/**
 * Ось символа — ровно как в `_brain/КОНТРАКТЫ.md` §4г, переписано оттуда
 * руками. Порядок здесь не важен, состав важен.
 */
const CONTRACT_SYMBOL_AXIS = [
  'registry-unreadable',
  'no-source',
  'source-disabled',
  'source-silent',
  'stale',
  'not-in-catalog',
  'threshold-unset',
];

/**
 * Ось канала — её называет **потребитель**, не мы. Перечень здесь для того,
 * чтобы было чем утверждать: ни одно из этих имён не должно оказаться в
 * нашей оси символа. Два словаря, схлопнутые в один, — это и есть то, что
 * §4г запрещает.
 */
const CONSUMER_CHANNEL_AXIS = ['not-configured', 'network', 'http-error', 'malformed', 'empty'];

/**
 * Ось служебной ручки — ровно как в §4г, переписана оттуда руками.
 *
 * **Этой сверки здесь не было, и это обнаружилось дорого.** §4г утверждает:
 * «эталон у `mds` выписан из этого раздела руками, поэтому правка §4г
 * краснит его тест». Для оси символа это было правдой, для этой оси — нет:
 * `ADMIN_CODES` проверялся только на стиль имён. 25.10 штаб внёс в §4г
 * `routing-identity-change` и ожидал красного — прогон остался зелёным.
 *
 * Это нулевой охват в чистом виде: проверка, не проверявшая состав,
 * выглядела как проверка, не нашедшая расхождений. Сверка стиля зелена при
 * любом составе, и именно поэтому она не замечает ни забытого имени, ни
 * заведённого мимо контракта.
 *
 * `no-token` и `bad-token` в §4г перечислены в общем ряду, а в коде живут
 * отдельным уточнением к `unauthorized` (`UNAUTHORIZED_DETAILS`): там это
 * `detail`, а не `code`. Поэтому состав сверяется с объединением двух
 * перечней — разделение у нас тоньше, чем в тексте, и это осознанно.
 */
const CONTRACT_ADMIN_AXIS = [
  'control-plane-disabled',
  'no-token',
  'bad-token',
  'registry-unreadable',
  'bad-body',
  'version-required',
  'version-conflict',
  'invalid-registry',
  'method-not-allowed',
  'not-found',
  'routing-identity-change',
];

/**
 * **Нынешние нарушители: имена, которые код отдаёт наружу, а §4г не знает.**
 *
 * Первое же включение этой сверки нашло расхождение, и оно настоящее, а не
 * опечатка в эталоне. `unauthorized` уходит в тело ответа как
 * `{ error: 'unauthorized', detail: 'no-token' | 'bad-token' }` — то есть
 * наружу видны **три** имени, а §4г перечисляет из них два. Потребитель,
 * написанный по контракту, встретит `unauthorized` и не найдёт его в своём
 * перечне.
 *
 * Эталон правим **не здесь**: он выписывается из контракта, а не из кода,
 * иначе сверка закрепит нашу ошибку и останется зелёной навсегда. Поэтому
 * расхождение стоит списком — правило, которому действительность ещё не
 * соответствует, ставят списком нарушителей, а не запретом.
 *
 * Список стерегут **с двух сторон** (второй тест ниже): новый нарушитель
 * краснит, и исчезнувший нарушитель, забытый в списке, краснит тоже. Когда
 * штаб решит — внести `unauthorized` в §4г или развести код и уточнение в
 * ответе, — список опустеет, и сверка сама станет строгой.
 *
 * Вынесено штабу 25.10 вместе с находкой «у этой оси не было сверки состава
 * вовсе»: §4г обещал, что его правка краснит наш тест, а для этой оси
 * проверялся только стиль имён. Правка §4г прошла, прогон остался зелёным.
 */
const ADMIN_AXIS_PENDING = ['unauthorized'];

describe('Словари машинных причин · стиль и состав (Р-087, §4г)', () => {
  it('ось символа совпадает с §4г по составу — ни лишних имён, ни забытых', () => {
    expect([...UNAVAILABLE_REASONS].sort()).toEqual([...CONTRACT_SYMBOL_AXIS].sort());
  });

  it('ось служебной ручки совпадает с §4г по составу — кроме объявленных нарушителей', () => {
    const inCode = [...ADMIN_CODES, ...UNAUTHORIZED_DETAILS];
    const allowed = [...CONTRACT_ADMIN_AXIS, ...ADMIN_AXIS_PENDING];
    expect([...inCode].sort()).toEqual([...allowed].sort());
  });

  it('список нарушителей стерегут с двух сторон: исчезнувший в нём не остаётся', () => {
    // Иначе список переживёт починку и будет молча разрешать имя, которого
    // в коде уже нет, — то есть превратится из долга в дыру.
    const inCode = new Set<string>([...ADMIN_CODES, ...UNAUTHORIZED_DETAILS]);
    const vanished = ADMIN_AXIS_PENDING.filter((code) => !inCode.has(code));
    expect(vanished).toEqual([]);
  });

  it('ось символа — kebab-case во всех именах', () => {
    const wrong = UNAVAILABLE_REASONS.filter((code) => !KEBAB.test(code));
    expect(wrong).toEqual([]);
  });

  it('причины маршрутизации — kebab-case: они уходят наружу в coverage.byReason', () => {
    const wrong = ROUTE_REASONS.filter((code) => !KEBAB.test(code));
    expect(wrong).toEqual([]);
  });

  it('коды служебной ручки — kebab-case, включая уточнение к unauthorized', () => {
    const wrong = [...ADMIN_CODES, ...UNAUTHORIZED_DETAILS].filter((code) => !KEBAB.test(code));
    expect(wrong).toEqual([]);
  });

  it('ось символа и ось канала не пересекаются: одно состояние — одно имя', () => {
    const overlap = UNAVAILABLE_REASONS.filter((code) =>
      (CONSUMER_CHANNEL_AXIS as string[]).includes(code),
    );
    expect(overlap).toEqual([]);
  });

  it('общие имена двух наших осей значат одно и то же, а не разное', () => {
    // `source-disabled` и `no-source` есть и в маршрутизации, и в ответе
    // `/v1/quotes` — это сознательно одно состояние под одним именем.
    // Любое ДРУГОЕ совпадение имён между осями — повод остановиться: два
    // словаря с общим словом и разным смыслом расходятся молча.
    const shared = ROUTE_REASONS.filter((code) =>
      (UNAVAILABLE_REASONS as readonly string[]).includes(code),
    );
    expect([...shared].sort()).toEqual(['no-source', 'source-disabled']);
  });
});
