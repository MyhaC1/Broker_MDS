/**
 * Контракт котировки. Сверен с `Quote` из `packages/realtime` сайта
 * (FeedDriver) — но **«один в один» уже неправда, и в обе стороны** (MDS-11):
 * `changePercent` у сайта обнуляем, у нас пока нет (`MDS-09`, ждёт очереди),
 * а `source` шлём мы, и в модели сайта его нет — он числится у них в списке
 * сознательно не читаемых и ждёт решения штаба.
 */
export interface Quote {
  symbol: string;
  name: string;
  category: 'forex' | 'metals' | 'crypto' | 'indices' | 'stocks' | 'energy';
  price: number;
  digits: number;
  changePercent: number;
  /**
   * Лучшая цена покупки и лучшая цена продажи (MDS-12).
   *
   * **Обнуляемые и обязательные.** Обнуляемые — потому что второй
   * поставщик их не даёт вовсе: `/quote` Twelve Data их не несёт, а во всей
   * их спецификации `bid`/`ask` встречаются в единственной схеме, цепочке
   * опционов. Обязательные — по доводу, который витрина проверила на себе:
   * необязательность прячет не только незнание значения, но и то, что
   * значение **забыли проставить**, а обязательное обнуляемое поле
   * заставляет компилятор назвать каждое место сборки котировки.
   *
   * **Пустота, а не ноль.** Нулевая цена покупки означала бы сделку по
   * нулю, отрицательная — то же с другой стороны. Не разобралось — `null`,
   * и это не то же самое, что «спреда нет».
   *
   * **Негодные лучшие цены тик НЕ отбрасывают.** Цена известна, лучшие
   * цены — нет; выбросить хорошую цену из-за непрочитанного стакана значило
   * бы потерять больше, чем мы не поняли. Это та же терпимость, что у
   * `changePercent` на стороне сайта, и законна она ровно потому, что
   * незнание здесь выразимо. Там, где оно невыразимо (`price`, `ts`),
   * терпимости нет и не будет.
   *
   * Живой кадр Binance `<symbol>@ticker` несёт их полями `b` и `a` —
   * проверено 25.10 сверкой с `@bookTicker` (совпадение до нуля по обеим
   * величинам) и замером охвата: 471 кадр из 471, нулевых и перекрещённых
   * ноль.
   */
  bid: number | null;
  ask: number | null;
  /** Unix ms последнего обновления */
  ts: number;
  /**
   * Какой источник произвёл этот тик (id из реестра провайдеров, Р-047).
   * Поле добавлено вместе с реестром и обязательно: при двух источниках на
   * символ цена без провенанса — это цена, про которую нельзя сказать, с чем
   * её сверять и по чьим условиям она получена. Смена значения на одном и том
   * же символе означает **смену источника цены**, то есть разрыв ряда, а не
   * очередной тик (ADR-031).
   */
  source: string;
}

/**
 * Сегмент внутри категории (таксономия платформы):
 * акции и индексы — по регионам (Европа/Азия/Америка/РФ),
 * валюта — по ликвидности (мажоры/миноры/экзотика).
 * Сырьё сегментов не имеет — «все возможные активы» одной группой
 * (metals/energy уже разведены на уровне category).
 */
export type Segment = 'europe' | 'asia' | 'america' | 'rf' | 'major' | 'minor' | 'exotic';

/** Инструмент каталога: канонический символ платформы + маппинг на провайдера. */
export interface CatalogInstrument {
  symbol: string;
  name: string;
  category: Quote['category'];
  /** null — категория без сегментов (крипта) */
  segment: Segment | null;
  digits: number;
  /**
   * id источника из реестра провайдеров (Р-047), а не закрытый перечень:
   * источников одного адаптера может быть несколько, и их имена — данные.
   * Какой код обслуживает источник, говорит `adapter` в реестре.
   */
  provider: string;
  providerSymbol: string;
}
